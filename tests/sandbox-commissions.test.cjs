const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {PGlite}=require('@electric-sql/pglite');
const ids=[1,2,3,4,5].map(n=>`${n}1111111-1111-4111-8111-111111111111`);
test('verified test deposits award 30/2/1 percent once, scope team reads, and reject unverified credits',async()=>{
 const db=new PGlite();
 try{
  await db.exec(`create role anon;create role authenticated;create schema auth;grant usage on schema auth to authenticated;
   create table auth.users(id uuid primary key,phone text);
   create function auth.uid() returns uuid language sql as $$select nullif(current_setting('test.customer_id',true),'')::uuid$$;
   create table profiles(id uuid primary key);
   create table team_members(id uuid primary key,invited_by uuid,created_at timestamptz default now());
   create table sandbox_wallets(user_id uuid primary key,remaining_balance numeric check(remaining_balance>=0),currency text);
   create table payment_transactions(id uuid primary key,user_id uuid,amount numeric,currency text default 'PHP',provider text default 'paymongo',transaction_type text default 'deposit',status text default 'pending');
   create table wallet_ledger(transaction_id uuid,user_id uuid,amount numeric,entry_type text);
   insert into profiles values ${ids.map(id=>`('${id}')`).join(',')};
   insert into auth.users values('${ids[1]}','+639000001821'),('${ids[3]}',null),('${ids[4]}','+639000009999');
   insert into team_members(id,invited_by) values('${ids[1]}','${ids[0]}'),('${ids[2]}','${ids[1]}'),('${ids[3]}','${ids[2]}'),('${ids[4]}','${ids[3]}');`);
  const sql=fs.readFileSync(path.join(__dirname,'../database/08_sandbox_referral_commissions.sql'),'utf8');
  await db.exec(sql);await db.exec(sql);
  await db.exec(fs.readFileSync(path.join(__dirname,'../database/09_team_member_deposits.sql'),'utf8'));
  await db.exec(fs.readFileSync(path.join(__dirname,'../database/11_team_member_commissions.sql'),'utf8'));
  const deposit=async(id,member,amount,verified=true)=>{
   await db.query('insert into payment_transactions(id,user_id,amount) values($1,$2,$3)',[id,member,amount]);
   if(verified)await db.query("insert into wallet_ledger values($1,$2,$3,'deposit_credit')",[id,member,amount]);
   await db.query("update payment_transactions set status='completed' where id=$1",[id]);
  };
  const tx='aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa';
  await deposit(tx,ids[3],1000);
  let rows=(await db.query('select level,amount_centavos from sandbox_referral_commissions order by level')).rows;
  assert.deepEqual(rows.map(r=>[r.level,Number(r.amount_centavos)]),[[1,30000],[2,2000],[3,1000]]);
  await db.query("update payment_transactions set status='completed' where id=$1",[tx]);
  await db.query("update payment_transactions set status='pending' where id=$1",[tx]);
  await db.query("update payment_transactions set status='completed' where id=$1",[tx]);
  assert.equal(Number((await db.query('select count(*) from sandbox_referral_commissions')).rows[0].count),3);
  await deposit('bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb',ids[3],1000,false);
  assert.equal(Number((await db.query('select count(*) from sandbox_referral_commissions')).rows[0].count),3);
  await deposit('cccccccc-cccc-4ccc-8ccc-cccccccccccc',ids[1],200.05);
  assert.equal(Number((await db.query('select amount_centavos from sandbox_referral_commissions where transaction_id=$1',['cccccccc-cccc-4ccc-8ccc-cccccccccccc'])).rows[0].amount_centavos),6001);
  await db.query('insert into payment_transactions(id,user_id,amount) values($1,$2,500)',['ffffffff-ffff-4fff-8fff-ffffffffffff',ids[1]]);
  await db.exec(`set test.customer_id='${ids[0]}';set role authenticated;`);
  const summary=(await db.query('select my_sandbox_team() as summary')).rows[0].summary;
  assert.equal(Number(summary.total_commission),70.01);
  assert.deepEqual(summary.levels.map(l=>[l.level,l.count]),[[1,1],[2,1],[3,1]]);
  assert.equal(summary.levels[2].members[0].id,ids[3]);
  assert.equal(summary.levels[0].members[0].phone_last4,'1821');
  assert.equal(Number(summary.levels[0].members[0].verified_deposits),200.05);
  assert.equal(Number(summary.levels[0].members[0].earned_commission),60.01);
  assert.equal(Number(summary.levels[2].members[0].earned_commission),10);
  assert.equal(Number(summary.levels[2].members[0].verified_deposits),1000);
  assert.equal(summary.levels[2].members[0].phone_last4,null);
  assert.equal(JSON.stringify(summary).includes('639000001821'),false);
  assert.equal(JSON.stringify(summary).includes(ids[4]),false);
  assert.equal(Number((await db.query('select count(*) from sandbox_referral_commissions')).rows[0].count),2);
  await assert.rejects(db.exec('delete from sandbox_referral_commissions'),/permission denied/);
  await db.exec('reset role');
  await db.exec(`alter table sandbox_wallets add constraint test_credit_failure check(user_id<>'${ids[1]}'::uuid or remaining_balance<=20)`);
  const failedTx='eeeeeeee-eeee-4eee-8eee-eeeeeeeeeeee';
  await assert.rejects(deposit(failedTx,ids[3],200));
  assert.equal((await db.query('select status from payment_transactions where id=$1',[failedTx])).rows[0].status,'pending');
  assert.equal(Number((await db.query('select count(*) from sandbox_referral_commissions where transaction_id=$1',[failedTx])).rows[0].count),0);
  assert.equal(Number((await db.query('select remaining_balance from sandbox_wallets where user_id=$1',[ids[2]])).rows[0].remaining_balance),300);
  await db.exec('alter table sandbox_wallets drop constraint test_credit_failure');
  await db.exec(`update team_members set invited_by='${ids[3]}' where id='${ids[2]}'`);
  await deposit('dddddddd-dddd-4ddd-8ddd-dddddddddddd',ids[3],200);
  rows=(await db.query('select beneficiary_id from sandbox_referral_commissions where transaction_id=$1',['dddddddd-dddd-4ddd-8ddd-dddddddddddd'])).rows;
  assert.deepEqual(rows.map(r=>r.beneficiary_id),[ids[2]]);
  await db.exec(`set test.customer_id=''`);
  await assert.rejects(db.query('select my_sandbox_team()'),/Authentication required/);
 }finally{await db.close();}
});
