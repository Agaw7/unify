const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {PGlite}=require('@electric-sql/pglite');
const admin='11111111-1111-4111-8111-111111111111',user='22222222-2222-4222-8222-222222222222',account='33333333-3333-4333-8333-333333333333';
const keys=[4,5,6,7].map(n=>`${n}4444444-4444-4444-8444-444444444444`);
test('withdrawal mode switches affect only new requests and never duplicate balance deductions',async()=>{
 const db=new PGlite();
 try{
  await db.exec(`create role anon;create role authenticated;create role service_role;create schema auth;
   create function auth.uid() returns uuid language sql as $$select '${user}'::uuid$$;
   create table profiles(id uuid primary key,role text);
   create table payment_accounts(id uuid primary key,user_id uuid,provider text);
   create table sandbox_wallets(user_id uuid primary key,remaining_balance numeric check(remaining_balance>=0));
   create table sandbox_withdrawal_requests(id uuid primary key default gen_random_uuid(),user_id uuid,amount numeric,currency text,status text check(status in ('reserved','processing','simulated_paid','cancelled','rejected')),payment_method text,created_at timestamptz default now());
   insert into profiles values('${admin}','admin'),('${user}','user');
   insert into payment_accounts values('${account}','${user}','gcash');insert into sandbox_wallets values('${user}',1000);`);
  await db.exec(fs.readFileSync(path.join(__dirname,'../database/02_sandbox_withdrawals.sql'),'utf8'));
  const migration=fs.readFileSync(path.join(__dirname,'../database/13_withdrawal_modes.sql'),'utf8');await db.exec(migration);await db.exec(migration);
  const request=async(key,amount=100,enabled=true)=>(await db.query('select request_configured_sandbox_withdrawal($1,$2,$3,$4,$5) as result',[user,amount,account,key,enabled])).rows[0].result;
  const set=async(mode,version,actor=admin)=>(await db.query('select set_sandbox_withdrawal_mode($1,$2,$3) as result',[actor,mode,version])).rows[0].result;
  await assert.rejects(set('automatic',1,user),/Administrator required/);
  await db.exec('set role authenticated');
  await assert.rejects(request(keys[0]),/permission denied/);
  await assert.rejects(db.query('select request_sandbox_withdrawal(100,$1,$2)',[account,keys[0]]),/permission denied/);
  await assert.rejects(set('automatic',1),/permission denied/);
  await db.exec('reset role;set role service_role');
  const manual=await request(keys[0]);assert.equal(manual.status,'reserved');assert.equal(manual.processing_mode,'admin_approval');
  assert.equal((await set('automatic',1)).version,2);
  assert.equal((await request(keys[0],100,false)).status,'reserved');
  await assert.rejects(request(keys[1],200,false),/simulation is disabled/);
  const automatic=await request(keys[1],200,true);assert.equal(automatic.status,'simulated_paid');assert.equal(automatic.processing_mode,'automatic');
  assert.equal((await set('admin_approval',2)).version,3);
  assert.equal((await request(keys[1],200,false)).replayed,true);
  const next=await request(keys[2]);assert.equal(next.status,'reserved');assert.equal(Number(next.remaining_balance),600);
  await assert.rejects(set('automatic',2),/Settings changed/);
  await assert.rejects(request(keys[0],200),/different details/);
  await assert.rejects(request(keys[3],1000),/Insufficient/);
  assert.equal((await set('automatic',3)).version,4);
  assert.equal((await set('automatic',4)).version,4);
  await assert.rejects(request(keys[3],100,false),/simulation is disabled/);
  await db.exec('reset role');
  assert.equal(Number((await db.query('select remaining_balance from sandbox_wallets')).rows[0].remaining_balance),600);
  assert.equal(Number((await db.query('select count(*) from sandbox_withdrawal_requests')).rows[0].count),3);
  assert.equal(Number((await db.query('select count(*) from sandbox_withdrawal_mode_audit')).rows[0].count),3);
  assert.equal((await db.query('select status from sandbox_withdrawal_requests where id=$1',[manual.id])).rows[0].status,'reserved');
  assert.equal((await db.query('select status from sandbox_withdrawal_requests where id=$1',[automatic.id])).rows[0].status,'simulated_paid');
 }finally{await db.close();}
});
